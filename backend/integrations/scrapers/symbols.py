# Active-symbols filter — drops unforecastable tickers (illiquid /
# delisted / right-shares with no history) from the iteration universe
# at module load. Keeps live + news + warm scrapers under their
# Cloud Run task timeouts.
#
# Source of truth: integrations/data/active_symbols.json, written by
# warm-4 _ingest_stocks() after each forecast run as the set of
# tickers that produced a prediction in stocks.json. Scraper bin/
# entrypoints download this from gs://etl_b/outputs/active_symbols.json
# before invoking the scraper module.
#
# Behavior:
# - File missing (first run / fresh checkout) → SYMBOLS = full universe.
# - File present                              → SYMBOLS = full ∩ active.
# - SCRAPER_LIMIT env var still wins (slicing applied last).
def _apply_active_filter(full_list):
    import json
    from pathlib import Path
    override = Path(__file__).resolve().parent.parent / "data" / "active_symbols.json"
    if not override.exists():
        return full_list
    try:
        active = set(json.loads(override.read_text()))
    except (ValueError, OSError):
        return full_list
    return [s for s in full_list if s in active]


